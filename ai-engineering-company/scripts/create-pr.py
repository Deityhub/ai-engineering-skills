#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Create PR with rich template including all validation gates.
"""

import argparse
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Optional


def run_cmd(cmd: List[str], cwd: Path = None) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)


def get_git_info(repo_path: Path) -> Dict:
    """Get current git status."""
    branch = run_cmd(["git", "branch", "--show-current"], repo_path).stdout.strip()
    sha = run_cmd(["git", "rev-parse", "HEAD"], repo_path).stdout.strip()[:8]
    status = run_cmd(["git", "status", "--porcelain"], repo_path).stdout.strip()
    return {"branch": branch, "sha": sha, "has_changes": bool(status)}


def generate_pr_body(context: Dict, validation_results: Dict) -> str:
    """Generate rich PR body template."""
    consensus = validation_results.get("consensus", {})

    gates = [
        ("Security Scan", validation_results.get("security", {}).get("passed", False)),
        ("Performance Baseline", validation_results.get("performance", {}).get("budget_met", False)),
        ("Architecture Review", validation_results.get("architecture", {}).get("approved", False)),
        ("Tests", validation_results.get("tests", {}).get("passed", False)),
        ("Accessibility Audit", validation_results.get("accessibility", {}).get("passed", False)),
        ("Terraform/K8s Validation", validation_results.get("infra", {}).get("valid", False)),
    ]

    gate_lines = []
    for name, passed in gates:
        status = "✅" if passed else "❌"
        gate_lines.append(f"- {status} {name}")

    consensus_status = "✅ APPROVED" if consensus.get("decision") == "approve" else "❌ REJECTED" if consensus.get("decision") == "reject" else "⏳ ESCALATED"
    quorum = "YES" if consensus.get("quorum_reached") else "NO"
    confidence = f"{consensus.get('confidence', 0):.0%}"

    return f"""## 🤖 AI Engineering Company — Automated PR

### Request
{context.get('request', 'Feature implementation')}

### DAG Execution
- **DAG ID**: {context.get('dag_id', 'N/A')}
- **Mode**: {context.get('mode', 'N/A')}
- **Skills Used**: {', '.join(context.get('skills', []))}

### Validation Gates
{chr(10).join(gate_lines)}

### Consensus
- **Decision**: {consensus_status}
- **Quorum**: {quorum} ({confidence} confidence)
- **Reasoning**: {consensus.get('reasoning', 'N/A')}

### Deployment Plan
- **Strategy**: Canary 5% → 25% → 100% over 2h
- **Rollback**: Single-click via feature flag
- **Monitoring**: SLO dashboards + burn rate alerts

### Checklist
- [ ] All validation gates passed
- [ ] Consensus reached (quorum ≥66%)
- [ ] Human approval for production deploy
- [ ] Feature flag created for rollout
- [ ] Runbook updated
- [ ] Changelog entry added

---
*Generated by AI Engineering Company*
"""


def main():
    parser = argparse.ArgumentParser(description="Create PR with validation gates")
    parser.add_argument("--title", required=True, help="PR title")
    parser.add_argument("--context", type=Path, help="Context JSON file")
    parser.add_argument("--validation", type=Path, help="Validation results JSON file")
    parser.add_argument("--base", default="main", help="Base branch")
    parser.add_argument("--draft", action="store_true", help="Create as draft")
    parser.add_argument("--repo", type=Path, default=Path.cwd(), help="Repo path")
    args = parser.parse_args()

    repo_path = args.repo.resolve()

    # Load context
    context = {}
    if args.context and args.context.exists():
        import json
        context = json.loads(args.context.read_text())

    # Load validation results
    validation = {}
    if args.validation and args.validation.exists():
        import json
        validation = json.loads(args.validation.read_text())

    # Get git info
    git_info = get_git_info(repo_path)

    # Generate PR body
    body = generate_pr_body(context, validation)

    # Create PR
    cmd = ["gh", "pr", "create", "--title", args.title, "--body", body, "--base", args.base]
    if args.draft:
        cmd.append("--draft")

    result = run_cmd(cmd, repo_path)

    if result.returncode == 0:
        print("✅ PR created successfully")
        print(result.stdout)
    else:
        print("❌ Failed to create PR")
        print(result.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()